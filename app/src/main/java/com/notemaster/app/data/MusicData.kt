    /** 大三/小三和弦的三音（相对 C4 的半音偏移），根音用音级 1..7 */
    fun chordNotes(rootStep: Int, minor: Boolean): List<Double> {
        val r = semitones[rootStep - 1]
        val third = if (minor) r + 3 else r + 4
        val fifth = r + 7
        val toC4 = { s: Int -> C4_FREQ * Math.pow(2.0, (s % 12) / 12.0) * (if (s >= 12) 2.0 else 1.0) }
        return listOf(toC4(r), toC4(third), toC4(fifth))
    }

    fun isMinorChord(rootStep: Int): Boolean = rootStep == 6 || rootStep == 2 || rootStep == 3

    fun chordLabel(rootStep: Int): String {
        val base = letters[rootStep - 1]
        return if (isMinorChord(rootStep)) base + "m" else base
    }

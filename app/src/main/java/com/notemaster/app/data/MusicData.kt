/**
 * 简谱（数字谱）核心数据模型与解析器。
 * 记法：1-7 基本音级；"^" 高八度；"_" 低八度；"-" 延长一拍；"0" 休止；"|" 小节线（忽略）。
 * 例如： 3 3 5 6 5 - | 3 2 1 _6 2 - 0
 */
data class JpNote(
    val step: Int,        // 1..7 = do..si；0 = 休止
    val octave: Int,      // 0 中音区，+1 高音，-1 低音
    var beats: Float      // 拍数
)

object MusicData {

    val solfege = listOf("哆", "来", "咪", "发", "嗦", "拉", "西")   // 1..7
    val letters = listOf("C", "D", "E", "F", "G", "A", "B")          // 1..7
    // 半音偏移（相对 C4）
    val semitones = listOf(0, 2, 4, 5, 7, 9, 11)
    const val C4_FREQ = 261.626

    fun stepToFreq(step: Int, octave: Int): Double {
        if (step <= 0) return 0.0
        val semi = semitones[step - 1] + octave * 12
        return C4_FREQ * Math.pow(2.0, semi / 12.0)
    }

    /** 显示用数字谱标记：高音加 ′，低音加 _，长音加 - */
    fun displayToken(n: JpNote): String {
        val core = when {
            n.step == 0 -> "0"
            n.octave > 0 -> "${n.step}′"
            n.octave < 0 -> "_${n.step}_"
            else -> "${n.step}"
        }
        return core + "-".repeat((n.beats - 1).toInt().coerceAtLeast(0))
    }

    /** 解析简谱字符串为音符列表 */
    fun parseMelody(text: String): List<JpNote> {
        val notes = mutableListOf<JpNote>()
        for (raw in text.trim().split(Regex("[\\s,]+"))) {
            val t = raw.trim()
            if (t.isEmpty() || t == "|") continue
            when {
                t == "-" -> notes.lastOrNull()?.let { it.beats += 1f }
                t == "0" -> notes.add(JpNote(0, 0, 1f))
                else -> {
                    val step = t.firstOrNull()?.digitToIntOrNull() ?: continue
                    if (step in 1..7) {
                        var oct = 0
                        if (t.contains('^') || t.contains('+')) oct = 1
                        if (t.contains('_') || t.contains('\'')) oct = -1
                        notes.add(JpNote(step, oct, 1f))
                    }
                }
            }
        }
        return notes
    }

